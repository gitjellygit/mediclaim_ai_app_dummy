export function permissionsForRole(role) {
  return new Set(ROLE_PERMISSIONS[String(role || "").toUpperCase()] || []);
}

export function hasPermission(userOrRole, permission) {
  const role =
    typeof userOrRole === "string" ? userOrRole : userOrRole?.role;
  return permissionsForRole(role).has(permission);
}

export function permissionList(userOrRole) {
  return [...permissionsForRole(
    typeof userOrRole === "string" ? userOrRole : userOrRole?.role
  )];
}
